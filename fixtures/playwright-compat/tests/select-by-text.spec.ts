// Workflow cases F4.1, F5.1, F7.1, F7.3 and F9.3 of docs/plans/public-beta/workflow-cases.md written again as a
// Playwright test most often writes them, naming each option of a select by its text alone. Playwright matches that
// text against each option's value and its label; Retest's compatibility refuses it by name, so each is a declared gap.
import { test, expect } from '@playwright/test'

test('adds a task with a title, notes and a priority, naming the priority by its text', async ({ page }) => {
  await page.goto('/workflow/tasks')
  await expect(page.getByTestId('task-count')).toHaveText('No tasks yet')
  await page.getByLabel('Title').fill('Release checklist')
  await page.getByLabel('Notes').fill('Check the changelog and the docs')
  await page.getByLabel('Priority').selectOption('High')
  await page.getByRole('button', { name: 'Add task' }).click()
  await expect(page.getByRole('status')).toHaveText('Task added')
  await expect(page.getByTestId('task-title')).toHaveText('Release checklist')
  await expect(page.getByTestId('task-priority')).toHaveText('High')
  await expect(page.getByTestId('task-notes')).toHaveText('Check the changelog and the docs')
  await expect(page.getByLabel('Title')).toHaveValue('')
  await expect(page.getByLabel('Priority')).toHaveValue('Normal')
  await page.reload()
  await expect(page.getByTestId('task-title')).toHaveText('Release checklist')
  await expect(page.getByTestId('task-count')).toHaveText('1 task')
})

test('edits a task and the change survives a reload, naming the priority by its text', async ({ page }) => {
  await page.goto('/workflow/backlog')
  await page.getByRole('button', { name: 'Edit Book venue' }).click()
  await expect(page.getByLabel('Title')).toHaveValue('Book venue')
  await page.getByLabel('Title').fill('Book the main hall')
  await page.getByLabel('Priority').selectOption('High')
  await page.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByTestId('item-title')).toHaveText(['Write release notes', 'Book the main hall', 'Order badges'])
  await expect(page.getByTestId('item-priority')).toHaveText(['High', 'High', 'Low'])
  await page.reload()
  await expect(page.getByTestId('item-title')).toHaveText(['Write release notes', 'Book the main hall', 'Order badges'])
  await expect(page.getByTestId('item-priority')).toHaveText(['High', 'High', 'Low'])
})

test('chooses a plan, ticks a box and picks a theme, naming the plan by its text', async ({ page }) => {
  await page.goto('/workflow/preferences')
  await expect(page.getByTestId('current')).toHaveText('plan=free seats=none updates=on summary=off alerts=on theme=light')
  await page.getByLabel('Plan').selectOption('Team')
  await expect(page.getByTestId('price')).toHaveText('$12 a month')
  await page.getByLabel('Weekly summary').check()
  await page.getByLabel('Dark').check()
  await expect(page.getByLabel('Weekly summary')).toBeChecked()
  await expect(page.getByLabel('Dark')).toBeChecked()
  await expect(page.getByTestId('current')).toHaveText('plan=team seats=none updates=on summary=on alerts=on theme=dark')
  await page.getByRole('button', { name: 'Save preferences' }).click()
  await expect(page.getByRole('status')).toHaveText('Saved plan=team seats=none updates=on summary=on alerts=on theme=dark')
  await page.reload()
  await expect(page.getByLabel('Plan')).toHaveValue('team')
  await expect(page.getByLabel('Weekly summary')).toBeChecked()
  await expect(page.getByLabel('Dark')).toBeChecked()
  await expect(page.getByTestId('current')).toHaveText('plan=team seats=none updates=on summary=on alerts=on theme=dark')
})

test('the Business plan shows a seats choice that the other plans hide, naming each option by its text', async ({ page }) => {
  await page.goto('/workflow/preferences')
  await expect(page.getByTestId('seats-field')).toBeHidden()
  await page.getByLabel('Plan').selectOption('Business')
  await expect(page.getByLabel('Seats')).toBeVisible()
  await page.getByLabel('Seats').selectOption('25 seats')
  await expect(page.getByTestId('current')).toHaveText('plan=business seats=25 updates=on summary=off alerts=on theme=light')
  await page.getByLabel('Plan').selectOption('Free')
  await expect(page.getByTestId('seats-field')).toBeHidden()
  await expect(page.getByTestId('price')).toHaveText('$0 a month')
})

test('a genre filter narrows a search, naming the genre by its text', async ({ page }) => {
  await page.goto('/workflow/catalog')
  await page.getByLabel('Search').fill('history')
  await page.getByRole('button', { name: 'Search' }).click()
  await expect(page.getByTestId('result-title')).toHaveText(['The Secret History', 'A Brief History of Time', 'A History of the World in 100 Objects'])
  await page.getByLabel('Genre').selectOption('History')
  await page.getByRole('button', { name: 'Search' }).click()
  await expect(page.getByTestId('result-count')).toHaveText('1 result')
  await expect(page.getByTestId('result-title')).toHaveText(['A History of the World in 100 Objects'])
  await page.getByLabel('Search').fill('zzzz')
  await page.getByLabel('Search').press('Enter')
  await expect(page.getByTestId('result-count')).toHaveText('No results')
  await expect(page.getByTestId('result-title')).toHaveCount(0)
  await expect(page.getByTestId('page-status')).toBeHidden()
})
